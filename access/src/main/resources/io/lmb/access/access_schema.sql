-- LMB access service schema. Portable subset of PostgreSQL and H2. Idempotent (IF NOT EXISTS), applied at every start.
-- Times are epoch milliseconds. Only the access service writes these tables.

-- One row (id 1): the directory version, bumped by every change in the same transaction.
CREATE TABLE IF NOT EXISTS access_meta (
  id INTEGER PRIMARY KEY,
  version BIGINT NOT NULL,
  bootstrapped_ms BIGINT NOT NULL,
  updated_ms BIGINT NOT NULL);

-- Throttle tiers: per session, new orders and replaces / every request.
CREATE TABLE IF NOT EXISTS access_tier (
  name VARCHAR(32) PRIMARY KEY,
  order_rate DOUBLE PRECISION NOT NULL,
  order_burst INTEGER NOT NULL,
  message_rate DOUBLE PRECISION NOT NULL,
  message_burst INTEGER NOT NULL,
  updated_ms BIGINT NOT NULL);

-- Teams. firm_id is the venue's firm id (the control plane's firm, which carries the risk limits).
CREATE TABLE IF NOT EXISTS access_firm (
  firm_id INTEGER PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  tier VARCHAR(32) NOT NULL,
  enabled BOOLEAN NOT NULL,
  created_ms BIGINT NOT NULL,
  updated_ms BIGINT NOT NULL);

-- Members: one order entry session each. tier NULL = the firm's.
CREATE TABLE IF NOT EXISTS access_session (
  session_id BIGINT PRIMARY KEY,
  firm_id INTEGER NOT NULL REFERENCES access_firm (firm_id),
  label VARCHAR(200) NOT NULL,
  tier VARCHAR(32),
  enabled BOOLEAN NOT NULL,
  created_ms BIGINT NOT NULL,
  updated_ms BIGINT NOT NULL);

-- API keys, as SHA-256 of the key. session_id 0 = any session of the firm. scopes: comma separated.
-- not_after_ms 0 = no expiry (a rotation sets it on the old key); revoked_ms 0 = not revoked.
CREATE TABLE IF NOT EXISTS access_key (
  key_id VARCHAR(32) PRIMARY KEY,
  firm_id INTEGER NOT NULL REFERENCES access_firm (firm_id),
  session_id BIGINT NOT NULL,
  sha256 VARCHAR(64) NOT NULL UNIQUE,
  scopes VARCHAR(200) NOT NULL,
  label VARCHAR(200) NOT NULL,
  created_ms BIGINT NOT NULL,
  not_after_ms BIGINT NOT NULL,
  revoked_ms BIGINT NOT NULL,
  replaced_by VARCHAR(32));

-- Every change, by operator.
CREATE TABLE IF NOT EXISTS access_audit (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts_ms BIGINT NOT NULL,
  actor VARCHAR(64) NOT NULL,
  action VARCHAR(32) NOT NULL,
  detail VARCHAR(4000) NOT NULL);

#!/usr/bin/env python3
"""Renders the Kubernetes manifests of the production shape. Standard library only (no Helm).

    python3 deploy/k8s/render.py           # write deploy/k8s/rendered/*.yaml
    python3 deploy/k8s/render.py check     # exit 1 if rendered/ is out of date, plus structural checks

Inputs: deploy/prod/site.json (shards, members, zones) and deploy/k8s/values-prod.json.
Outputs (rendered/): 00-base.yaml (namespace, priority class, storage class, topology ConfigMap),
10-shards.yaml (per shard: headless Service, StatefulSet, PodDisruptionBudget), 20-services.yaml
(gateways, market data, consolidators, control plane, post-trade, ledger, replayers), 30-dr-backup.yaml
(for the DR region's cluster). Secrets are not rendered: create `lmb-secrets` (keys cluster-secret,
db-url, db-user, db-password, ledger-db-url, ledger-db-user, ledger-db-password, admin-token) with your
secret manager.

Design notes (docs/operations.md 2.3): one StatefulSet per shard, 3 replicas spread one per zone,
hostNetwork for the latency path, Guaranteed QoS with integer CPUs, local NVMe PVs, the Aeron C driver
as a native sidecar sharing a memory-backed /dev/shm, OnDelete updates, no liveness probe on matchers.
All members of a shard use the same ports (basePort 20000 + 100*shard) so one pod template fits;
hard anti-affinity keeps two members of a shard off the same host.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "deploy", "monitoring"))
from render import to_yaml  # noqa: E402  (deploy/monitoring/render.py)

OUT = os.path.join(HERE, "rendered")
HEADER = "# GENERATED by deploy/k8s/render.py from deploy/prod/site.json and values-prod.json. Do not edit.\n"


def load():
    with open(os.path.join(ROOT, "deploy", "prod", "site.json")) as f:
        site = json.load(f)
    with open(os.path.join(HERE, "values-prod.json")) as f:
        vals = json.load(f)
    return site, vals


def base_port(s):
    return 20000 + 100 * s


def svc_dns(name, svc, v):
    return f"{name}.{svc}.{v['namespace']}.svc.{v['clusterDomain']}"


# ---------------------------------------------------------------------------------------------------
def topology(site, v):
    shards, members = site["shards"], site["membersPerShard"]
    lines = [f"lmb.shards={shards}", f"lmb.members={members}"]
    for s in range(shards):
        for m in range(members):
            lines.append(f"lmb.shard.{s}.member.{m}.host={svc_dns(f'lmb-shard-{s}-{m}', f'lmb-shard-{s}', v)}")
            lines.append(f"lmb.shard.{s}.member.{m}.basePort={base_port(s)}")
    g = v["gateway"]["replicas"]
    lines.append(f"lmb.gateways={g}")
    for i in range(g):
        lines += [f"lmb.gateway.{i}.host={svc_dns(f'lmb-gateway-{i}', 'lmb-gateway', v)}",
                  f"lmb.gateway.{i}.grpcPort=9100", f"lmb.gateway.{i}.fixPort=9200", f"lmb.gateway.{i}.metricsPort=9300"]
    lines.append("lmb.md.instances=2")
    for i in range(2):
        lines += [f"lmb.md.{i}.host={svc_dns(f'lmb-marketdata-{i}', 'lmb-marketdata', v)}",
                  f"lmb.md.{i}.retransmitPort=9500", f"lmb.md.{i}.grpcPort=9510", f"lmb.md.{i}.metricsPort=9520"]
    lines.append("lmb.consolidators=2")
    lines += [f"lmb.consolidator.{i}.metricsPort=9600" for i in range(2)]
    lines.append("lmb.controlplane.instances=2")
    for i in range(2):
        lines += [f"lmb.controlplane.{i}.host={svc_dns(f'lmb-controlplane-{i}', 'lmb-controlplane', v)}",
                  f"lmb.controlplane.{i}.restPort=9700", f"lmb.controlplane.{i}.metricsPort=9710"]
    lines += ["lmb.posttrade.dropCopyFixPort=9800", "lmb.posttrade.metricsPort=9810", "lmb.ledger.metricsPort=9820",
              "lmb.replayer.metricsPort=9900",
              "lmb.feedsim.instances=0",
              "lmb.symbols=/etc/lmb/refdata/symbols.csv", "lmb.firms=/etc/lmb/refdata/firms.csv"]
    return "\n".join(lines) + "\n"


def dr_topology(site, v):
    """The DR cluster reaches the primary members through externally published per-member DNS names
    (ExternalDNS or static records for the hostNetwork pods), same ports."""
    lines = [f"lmb.shards={site['shards']}", f"lmb.members={site['membersPerShard']}"]
    for s in range(site["shards"]):
        for m in range(site["membersPerShard"]):
            lines.append(f"lmb.shard.{s}.member.{m}.host=lmb-shard-{s}-{m}.{v['externalDomain']}")
            lines.append(f"lmb.shard.{s}.member.{m}.basePort={base_port(s)}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------------------------------
def res(cpu, mem, huge=None):
    r = {"cpu": str(cpu), "memory": mem}
    if huge:
        r["hugepages-2Mi"] = huge
    return {"requests": dict(r), "limits": dict(r)}


def labels(component, extra=None):
    lab = {"app.kubernetes.io/name": "lmb", "app.kubernetes.io/component": component}
    lab.update(extra or {})
    return lab


def aeronmd_sidecar(v, cpu, mem, name):
    return {
        "name": "aeronmd", "image": v["aeronmdImage"], "restartPolicy": "Always",
        "env": [{"name": "AERON_DIR", "value": "/dev/shm/aeron"},
                {"name": "AERON_THREADING_MODE", "value": "DEDICATED" if cpu >= 3 else "SHARED_NETWORK"},
                {"name": "AERON_CONDUCTOR_IDLE_STRATEGY", "value": "backoff"},
                {"name": "AERON_SENDER_IDLE_STRATEGY", "value": "noop"},
                {"name": "AERON_RECEIVER_IDLE_STRATEGY", "value": "noop"},
                {"name": "AERON_SOCKET_SO_RCVBUF", "value": "4194304"},
                {"name": "AERON_SOCKET_SO_SNDBUF", "value": "4194304"},
                {"name": "AERON_RCV_INITIAL_WINDOW_LENGTH", "value": "4194304"},
                {"name": "AERON_DRIVER_TIMEOUT", "value": "10000"},
                {"name": "AERON_DIR_DELETE_ON_START", "value": "1"}],
        "resources": res(cpu, mem),
        "startupProbe": {"exec": {"command": ["test", "-f", "/dev/shm/aeron/cnc.dat"]},
                         "periodSeconds": 1, "failureThreshold": 30},
        "securityContext": {"allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"], "add": ["IPC_LOCK", "SYS_NICE"]}},
        "volumeMounts": [{"name": "shm", "mountPath": "/dev/shm"}],
    }


def pod_spec(v, component, cfg, containers, init=None, host_network=True, extra_volumes=None,
             anti_affinity_labels=None, zone_terms=None, spread_labels=None):
    spec = {
        "priorityClassName": "lmb-critical" if host_network else "lmb-standard",
        "terminationGracePeriodSeconds": 60,
        "enableServiceLinks": False,
        "nodeSelector": {"lmb.io/pool": cfg["pool"]},
        "tolerations": [{"key": "lmb.io/dedicated", "operator": "Equal", "value": cfg["pool"], "effect": "NoSchedule"}],
        "securityContext": {"runAsUser": 10001, "runAsGroup": 10001, "fsGroup": 10001, "runAsNonRoot": True},
        "containers": containers,
        "volumes": [{"name": "config", "configMap": {"name": "lmb-topology"}},
                    {"name": "logs", "emptyDir": {"sizeLimit": "20Gi"}}] + (extra_volumes or []),
    }
    if host_network:
        spec["hostNetwork"] = True
        spec["dnsPolicy"] = "ClusterFirstWithHostNet"
    if init:
        spec["initContainers"] = init
    aff = {}
    if anti_affinity_labels:
        aff["podAntiAffinity"] = {"requiredDuringSchedulingIgnoredDuringExecution": [
            {"labelSelector": {"matchLabels": anti_affinity_labels}, "topologyKey": "kubernetes.io/hostname"}]}
    if zone_terms:
        aff["nodeAffinity"] = {"requiredDuringSchedulingIgnoredDuringExecution": {"nodeSelectorTerms": [
            {"matchExpressions": [{"key": "topology.kubernetes.io/zone", "operator": "In", "values": zone_terms}]}]}}
    if aff:
        spec["affinity"] = aff
    if spread_labels:
        spec["topologySpreadConstraints"] = [{
            "maxSkew": 1, "minDomains": 3, "topologyKey": "topology.kubernetes.io/zone",
            "whenUnsatisfiable": "DoNotSchedule", "labelSelector": {"matchLabels": spread_labels}}]
    return spec


def lmb_container(v, service, cfg, env, metrics_port, ports, mounts, huge=None, external_driver=True, ready=True):
    e = [{"name": "POD_NAME", "valueFrom": {"fieldRef": {"fieldPath": "metadata.name"}}},
         {"name": "LMB_HEAP", "value": cfg["heap"]},
         {"name": "LMB_EXTERNAL_DRIVER", "value": "1" if external_driver else "0"},
         {"name": "LMB_CLUSTER_SECRET", "valueFrom": {"secretKeyRef": {"name": v["secretName"], "key": "cluster-secret"}}}]
    if external_driver:
        e.append({"name": "LMB_AERON_DIR", "value": "/dev/shm/aeron"})
    if huge:
        e.append({"name": "LMB_LARGE_PAGES", "value": "1"})
    e += [{"name": k, "value": str(val)} for k, val in env.items()]
    c = {
        "name": service, "image": v["image"], "args": [service], "env": e,
        "resources": res(cfg["cpu"], cfg["memory"], huge),
        "ports": [{"name": n, "containerPort": p, "protocol": proto} for n, p, proto in ports],
        "securityContext": {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True,
                            "capabilities": {"drop": ["ALL"], "add": ["IPC_LOCK", "SYS_NICE"]}},
        "volumeMounts": [{"name": "config", "mountPath": "/etc/lmb/topology.properties", "subPath": "topology.properties"},
                         {"name": "config", "mountPath": "/etc/lmb/refdata/symbols.csv", "subPath": "symbols.csv"},
                         {"name": "config", "mountPath": "/etc/lmb/refdata/firms.csv", "subPath": "firms.csv"},
                         {"name": "logs", "mountPath": "/var/log/lmb"}] + mounts,
    }
    if ready:
        c["readinessProbe"] = {"httpGet": {"path": "/metrics", "port": metrics_port}, "periodSeconds": 5, "failureThreshold": 3}
    return c


def statefulset(v, name, component, replicas, pod_labels, spec, svc_name, pvc=None, metrics_port=None, parallel=True):
    ss = {
        "apiVersion": "apps/v1", "kind": "StatefulSet",
        "metadata": {"name": name, "namespace": v["namespace"], "labels": pod_labels},
        "spec": {
            "serviceName": svc_name, "replicas": replicas,
            "podManagementPolicy": "Parallel" if parallel else "OrderedReady",
            "updateStrategy": {"type": "OnDelete"},
            "persistentVolumeClaimRetentionPolicy": {"whenDeleted": "Retain", "whenScaled": "Retain"},
            "selector": {"matchLabels": pod_labels},
            "template": {"metadata": {"labels": pod_labels,
                                      "annotations": {"prometheus.io/scrape": "true", "prometheus.io/port": str(metrics_port)}},
                         "spec": spec},
        },
    }
    if pvc:
        ss["spec"]["volumeClaimTemplates"] = [{
            "metadata": {"name": "data"},
            "spec": {"accessModes": ["ReadWriteOnce"], "storageClassName": pvc[1],
                     "resources": {"requests": {"storage": pvc[0]}}}}]
    return ss


def headless(v, name, sel, ports):
    return {"apiVersion": "v1", "kind": "Service",
            "metadata": {"name": name, "namespace": v["namespace"], "labels": sel},
            "spec": {"clusterIP": "None", "publishNotReadyAddresses": True, "selector": sel,
                     "ports": [{"name": n, "port": p, "protocol": proto} for n, p, proto in ports]}}


def pdb(v, name, sel, max_unavailable=1):
    return {"apiVersion": "policy/v1", "kind": "PodDisruptionBudget",
            "metadata": {"name": name, "namespace": v["namespace"]},
            "spec": {"maxUnavailable": max_unavailable, "selector": {"matchLabels": sel}}}


# ---------------------------------------------------------------------------------------------------
def base_docs(site, v):
    with open(os.path.join(ROOT, "deploy", "local", "symbols.csv")) as f:
        symbols = f.read()
    with open(os.path.join(ROOT, "deploy", "local", "firms.csv")) as f:
        firms = f.read()
    ns = v["namespace"]
    return [
        {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": ns, "labels": {"pod-security.kubernetes.io/enforce": "privileged"}}},
        {"apiVersion": "scheduling.k8s.io/v1", "kind": "PriorityClass", "metadata": {"name": "lmb-critical"},
         "value": 1000000000, "preemptionPolicy": "Never", "description": "LMB latency path: never preempted by other workloads"},
        {"apiVersion": "scheduling.k8s.io/v1", "kind": "PriorityClass", "metadata": {"name": "lmb-standard"},
         "value": 100000, "description": "LMB support services"},
        {"apiVersion": "storage.k8s.io/v1", "kind": "StorageClass", "metadata": {"name": v["storageClass"]},
         "provisioner": "kubernetes.io/no-provisioner", "volumeBindingMode": "WaitForFirstConsumer", "reclaimPolicy": "Retain"},
        {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "lmb-topology", "namespace": ns},
         "data": {"topology.properties": topology(site, v),
                  "symbols.csv": symbols, "firms.csv": firms,
                  "README": "symbols.csv/firms.csv are the sample reference data; production renders them from the control plane database at start of day.\n"}},
    ]


def shard_docs(site, v):
    docs = []
    n = v["node"]
    members = site["membersPerShard"]
    for s in range(site["shards"]):
        bp = base_port(s)
        mport = bp + 9
        sel = labels("node", {"lmb.io/shard": str(s)})
        ports = [("archive-ctl", bp + 0, "UDP"), ("archive-repl", bp + 1, "UDP"), ("ingress", bp + 2, "UDP"),
                 ("consensus", bp + 3, "UDP"), ("log", bp + 4, "UDP"), ("catchup", bp + 5, "UDP"),
                 ("event-ctl", bp + 6, "UDP"), ("archive-resp", bp + 7, "UDP"), ("backup", bp + 8, "UDP"),
                 ("metrics", mport, "TCP")]
        env = dict(n["env"], LMB_SHARD_ID=str(s), LMB_PIN=n["pin"])
        node = lmb_container(v, "node", n, env, mport, ports,
                             [{"name": "data", "mountPath": "/var/lib/lmb"}, {"name": "shm", "mountPath": "/dev/shm"},
                              {"name": "hugepages", "mountPath": "/hugepages"}], huge=n["hugepages2Mi"])
        vols = [{"name": "shm", "emptyDir": {"medium": "Memory", "sizeLimit": n["shmSize"]}},
                {"name": "hugepages", "emptyDir": {"medium": "HugePages"}}]
        spec = pod_spec(v, "node", n, [node], init=[aeronmd_sidecar(v, n["driverCpu"], n["driverMemory"], "node")],
                        extra_volumes=vols, anti_affinity_labels=sel, spread_labels=sel)
        name = f"lmb-shard-{s}"
        docs.append(headless(v, name, sel, ports))
        if v.get("statefulSetPerMember"):
            for m in range(members):
                msel = dict(sel, **{"lmb.io/member": str(m)})
                mspec = json.loads(json.dumps(spec))
                mspec.pop("topologySpreadConstraints", None)
                mspec["nodeSelector"]["topology.kubernetes.io/zone"] = site["primary"]["zones"][m]
                mspec["containers"][0]["env"].append({"name": "LMB_MEMBER_ID", "value": str(m)})
                docs.append(statefulset(v, f"{name}-m{m}", "node", 1, msel, mspec, name, (n["storage"], v["storageClass"]), mport))
        else:
            docs.append(statefulset(v, name, "node", members, sel, spec, name, (n["storage"], v["storageClass"]), mport))
        docs.append(pdb(v, name, sel))
    return docs


def service_docs(site, v):
    docs = []
    zones = site["primary"]["zones"]
    specs = [
        ("gateway", v["gateway"]["replicas"], [("grpc", 9100, "TCP"), ("fix", 9200, "TCP"), ("metrics", 9300, "TCP")], 9300, True),
        ("marketdata", v["marketdata"]["replicas"], [("retransmit", 9500, "TCP"), ("grpc", 9510, "TCP"), ("metrics", 9520, "TCP")], 9520, True),
        ("consolidator", v["consolidator"]["replicas"], [("metrics", 9600, "TCP")], 9600, True),
        ("controlplane", v["controlplane"]["replicas"], [("rest", 9700, "TCP"), ("metrics", 9710, "TCP")], 9710, False),
        ("posttrade", v["posttrade"]["replicas"], [("dropcopy", 9800, "TCP"), ("metrics", 9810, "TCP")], 9810, False),
        # exactly one ledger: it is the only writer of its tables
        ("ledger", 1, [("metrics", 9820, "TCP")], 9820, False),
        ("replayer", site["shards"], [("metrics", 9900, "TCP")], 9900, False),
    ]
    for comp, replicas, ports, mport, ext_driver in specs:
        cfg = v[comp]
        sel = labels(comp)
        zone = cfg.get("zone")
        zone_terms = [zones[0]] if zone == "leader" else [zones[-1]] if zone == "last" else None
        env = {}
        if comp == "controlplane":
            env = {}
        c = lmb_container(v, comp, cfg, env, mport, ports,
                          ([{"name": "data", "mountPath": "/var/lib/lmb"}] if cfg.get("storage") else
                           [{"name": "scratch", "mountPath": "/var/lib/lmb"}]) +
                          ([{"name": "shm", "mountPath": "/dev/shm"}]),
                          external_driver=ext_driver)
        if comp == "controlplane":
            c["env"] += [{"name": k, "valueFrom": {"secretKeyRef": {"name": v["secretName"], "key": key}}}
                         for k, key in (("LMB_DB_URL", "db-url"), ("LMB_DB_USER", "db-user"), ("LMB_DB_PASSWORD", "db-password"),
                                        ("LMB_CONTROLPLANE_ADMINTOKEN", "admin-token"))]
        if comp == "ledger":
            c["env"] += [{"name": k, "valueFrom": {"secretKeyRef": {"name": v["secretName"], "key": key}}}
                         for k, key in (("LMB_LEDGER_DB_URL", "ledger-db-url"), ("LMB_LEDGER_DB_USER", "ledger-db-user"),
                                        ("LMB_LEDGER_DB_PASSWORD", "ledger-db-password"))]
        if comp == "replayer":
            c["env"].append({"name": "LMB_REPLAYER_METRICSPORT", "value": "9900"})
        vols = [{"name": "shm", "emptyDir": {"medium": "Memory", "sizeLimit": "2Gi"}}]
        if not cfg.get("storage"):
            vols.append({"name": "scratch", "emptyDir": {"sizeLimit": "50Gi"}})
        init = [aeronmd_sidecar(v, cfg["driverCpu"], "1Gi", comp)] if ext_driver else None
        spec = pod_spec(v, comp, cfg, [c], init=init, host_network=cfg.get("hostNetwork", False), extra_volumes=vols,
                        anti_affinity_labels=sel if comp != "replayer" else None, zone_terms=zone_terms,
                        spread_labels=sel if zone == "spread" else None)
        if zone == "spread":
            spec["topologySpreadConstraints"][0]["minDomains"] = min(replicas, 3)
        name = f"lmb-{comp}"
        docs.append(headless(v, name, sel, ports))
        pvc = (cfg["storage"], cfg.get("storageClass", v["storageClass"])) if cfg.get("storage") else None
        docs.append(statefulset(v, name, comp, replicas, sel, spec, name, pvc, mport))
        if comp in ("gateway", "marketdata", "controlplane", "posttrade"):
            docs.append(pdb(v, name, sel))
    # admin REST for operators (any control plane instance accepts admin calls)
    docs.append({"apiVersion": "v1", "kind": "Service",
                 "metadata": {"name": "lmb-admin", "namespace": v["namespace"]},
                 "spec": {"selector": labels("controlplane"), "ports": [{"name": "rest", "port": 9700, "targetPort": 9700}]}})
    return docs


def dr_docs(site, v):
    b = v["backup"]
    sel = labels("backup")
    ns = v["namespace"]
    c = lmb_container(v, "backup", b, {}, 9910, [("metrics", 9910, "TCP")],
                      [{"name": "data", "mountPath": "/var/lib/lmb"}, {"name": "shm", "mountPath": "/dev/shm"}],
                      ready=False)
    c["env"].append({"name": "LMB_BACKUP_HOST", "valueFrom": {"fieldRef": {"fieldPath": "status.hostIP"}}})
    c["volumeMounts"][0]["name"] = "dr-config"
    spec = pod_spec(v, "backup", b, [c], init=[aeronmd_sidecar(v, 2, "1Gi", "backup")], host_network=True,
                    extra_volumes=[{"name": "shm", "emptyDir": {"medium": "Memory", "sizeLimit": "4Gi"}},
                                   {"name": "dr-config", "configMap": {"name": "lmb-topology-dr"}}],
                    anti_affinity_labels=sel)
    return [
        {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "lmb-topology-dr", "namespace": ns},
         "data": {"topology.properties": dr_topology(site, v)}},
        headless(v, "lmb-backup", sel, [("metrics", 9910, "TCP")]),
        statefulset(v, "lmb-backup", "backup", site["shards"], sel, spec, "lmb-backup", (b["storage"], v["storageClass"]), 9910),
    ]


def outputs():
    site, v = load()

    def multi(docs):
        return HEADER + "".join("---\n" + to_yaml(d) + "\n" for d in docs)
    return {
        "00-base.yaml": multi(base_docs(site, v)),
        "10-shards.yaml": multi(shard_docs(site, v)),
        "20-services.yaml": multi(service_docs(site, v)),
        "30-dr-backup.yaml": multi(dr_docs(site, v)),
    }


def structural_checks(files):
    """What kubectl --dry-run=client would catch first, without kubectl: required fields, Guaranteed QoS
    on the latency path, selectors matching templates, spread on shards."""
    import yaml  # PyYAML, only for the checks
    problems = []
    for fname, text in files.items():
        for d in yaml.safe_load_all(text):
            if not d:
                continue
            where = f"{fname}:{d.get('kind')}/{d.get('metadata', {}).get('name')}"
            for k in ("apiVersion", "kind", "metadata"):
                if k not in d:
                    problems.append(f"{where}: missing {k}")
            if d["kind"] != "StatefulSet":
                continue
            spec = d["spec"]
            tmpl = spec["template"]
            if any(tmpl["metadata"]["labels"].get(k) != val for k, val in spec["selector"]["matchLabels"].items()):
                problems.append(f"{where}: selector does not match template labels")
            pod = tmpl["spec"]
            if pod.get("hostNetwork"):
                for c in pod["containers"] + pod.get("initContainers", []):
                    r = c.get("resources", {})
                    if r.get("requests") != r.get("limits"):
                        problems.append(f"{where}/{c['name']}: requests != limits (not Guaranteed QoS)")
                    cpu = str(r.get("limits", {}).get("cpu", ""))
                    if not cpu.isdigit():
                        problems.append(f"{where}/{c['name']}: cpu '{cpu}' is not an integer (no exclusive cores)")
                if pod.get("dnsPolicy") != "ClusterFirstWithHostNet":
                    problems.append(f"{where}: hostNetwork without ClusterFirstWithHostNet")
            if d["metadata"]["name"].startswith("lmb-shard-"):
                if "livenessProbe" in pod["containers"][0]:
                    problems.append(f"{where}: matcher must not have a liveness probe")
                if not pod.get("topologySpreadConstraints") and spec["replicas"] > 1:
                    problems.append(f"{where}: no zone spread")
                if spec["updateStrategy"]["type"] != "OnDelete":
                    problems.append(f"{where}: shards must use OnDelete")
    return problems


def main():
    files = outputs()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        stale = [n for n, c in files.items() if not os.path.exists(os.path.join(OUT, n))
                 or open(os.path.join(OUT, n)).read() != c]
        problems = structural_checks(files)
        for p in problems:
            print("problem: " + p)
        if stale:
            print("out of date (run python3 deploy/k8s/render.py): " + ", ".join(stale))
        if not stale and not problems:
            print("deploy/k8s/rendered is up to date and passes the structural checks")
        return 1 if stale or problems else 0
    os.makedirs(OUT, exist_ok=True)
    for n, c in files.items():
        with open(os.path.join(OUT, n), "w") as f:
            f.write(c)
        print("wrote deploy/k8s/rendered/" + n)
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Production topology for bare metal: deploy/prod/site.json -> topology-prod.properties (primary
region, 3 AZs, leaders' AZ first) and topology-dr.properties (the same shards in the DR region, used
when DR is activated). Standard library only.

    python3 deploy/prod/render.py          # write both files next to this script
    python3 deploy/prod/render.py check    # exit 1 if they are out of date

Placement rules encoded here:
- member m of every shard lives in zones[m] (zones[0] is the leaders' zone), one member per host per
  shard; `membersPerHost` members of *different* shards share a matcher host (default 1: dedicated).
- gateways, both market data publishers (A and B on different hosts) and the consolidators sit in the
  leaders' zone; control plane instance i and post-trade instance i in zones[i]; replayers in the last
  zone (away from the leaders, they re-execute the log).
- ports keep the io.lmb.common.Topology defaults, so every member of every shard has distinct ports
  even when hosts are shared.
- `lmb.shard.S.member.M.zone` is not read by Topology (contract change request); monitoring uses it.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def build(site, region_key):
    region = site[region_key]
    dom = region["domain"]
    zones = region["zones"]
    shards = site["shards"]
    members = site["membersPerShard"]
    per_host = site.get("membersPerHost", 1)
    assert members <= len(zones), "one member per zone needs at least as many zones as members"
    lines = [
        f"# GENERATED by deploy/prod/render.py from site.json ({region_key}: {region['name']}). Do not edit.",
        f"# {shards} shards x {members} members over zones {', '.join(zones)}; leaders steered to {zones[0]}.",
        "lmb.shards=%d" % shards,
        "lmb.members=%d" % members,
        "",
        "# ---- shard members: host per member, zone for monitoring (ports: Topology defaults) ----",
    ]
    for s in range(shards):
        for m in range(members):
            z = zones[m]
            host_no = s // per_host + 1
            lines.append(f"lmb.shard.{s}.member.{m}.host=mx-{z}-{host_no:02d}.{dom}")
            lines.append(f"lmb.shard.{s}.member.{m}.zone={z}")
    lz = zones[0]
    g = site["gateways"]
    lines += ["", "# ---- gateways, market data, NBBO: in the leaders' zone ----", f"lmb.gateways={g}"]
    lines += [f"lmb.gateway.{i}.host=gw-{lz}-{i + 1:02d}.{dom}" for i in range(g)]
    lines += ["lmb.md.instances=2", f"lmb.md.0.host=md-{lz}-a.{dom}", f"lmb.md.1.host=md-{lz}-b.{dom}"]
    lines += ["# no feed simulator in production (replaced by the ticker plant adapter); monitoring key only",
              "lmb.feedsim.instances=0"]
    lines += ["lmb.consolidators=2"] + [f"lmb.consolidator.{i}.host=nbbo-{lz}-{i + 1:02d}.{dom}" for i in range(2)]
    lines += ["", "# ---- control plane and post-trade: one per zone ----", "lmb.controlplane.instances=2"]
    lines += [f"lmb.controlplane.{i}.host=cp-{zones[i]}-01.{dom}" for i in range(2)]
    lines += ["# lmb.posttrade.instances / .<i>.host are not Topology keys yet (contract change request 2)",
              "lmb.posttrade.instances=2"] + [f"lmb.posttrade.{i}.host=pt-{zones[i]}-01.{dom}" for i in range(2)]
    lines += ["", f"# ---- shadow replayers (one per shard) in {zones[-1]}; not Topology keys (monitoring only) ----"]
    lines += [f"lmb.replayer.{s}.host=rp-{zones[-1]}-{s // 8 + 1:02d}.{dom}" for s in range(shards)]
    lines += [f"lmb.replayer.{s}.metricsPort={9900 + s}" for s in range(shards)]
    lines += ["", "# ---- reference data (rendered by the control plane from PostgreSQL at start of day) ----",
              "lmb.symbols=/etc/lmb/refdata/symbols.csv", "lmb.firms=/etc/lmb/refdata/firms.csv"]
    if region_key == "primary":
        dr = site["dr"]
        lines += ["", f"# ---- DR: ClusterBackup per shard in {dr['name']} (async; RPO = backup lag) ----",
                  "# ClusterBackupMain reads lmb.backup.host (its own endpoint) per process; set it in the",
                  "# instance's environment (LMB_BACKUP_HOST). Hosts below are for monitoring and runbooks.",]
        lines += [f"lmb.dr.{s}.host=bk-{dr['zones'][0]}-{s // 8 + 1:02d}.{dr['domain']}" for s in range(shards)]
    return "\n".join(lines) + "\n"


def outputs():
    with open(os.path.join(HERE, "site.json")) as f:
        site = json.load(f)
    return {"topology-prod.properties": build(site, "primary"), "topology-dr.properties": build(site, "dr")}


def main():
    files = outputs()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        stale = [n for n, c in files.items() if not os.path.exists(os.path.join(HERE, n))
                 or open(os.path.join(HERE, n)).read() != c]
        print("out of date: " + ", ".join(stale) if stale else "deploy/prod topologies are up to date")
        return 1 if stale else 0
    for n, c in files.items():
        with open(os.path.join(HERE, n), "w") as f:
            f.write(c)
        print("wrote deploy/prod/" + n)
    return 0


if __name__ == "__main__":
    sys.exit(main())

# recording rules: the only place raw names are used
QUANTS = [("p50", "Q_P50"), ("p99", "Q_P99"), ("p999", "Q_P999"), ("max", "Q_MAX")]


def recording_rules(n):
    ql = n["QUANTILE_LABEL"]
    lat = n["LATENCY_TO_SECONDS"]
    sl = n["SHARD_LABEL"]
    rules = []

    def rec(name, expr):
        rules.append({"record": name, "expr": expr})

    def quantiles(key, name, by):
        if not n.get(key):
            return
        for short, qk in QUANTS:
            rec(f"lmb:{name}:{short}", f'max {by}({n[key]}{{{ql}="{n[qk]}"}}) * {lat}')

    quantiles("GATEWAY_ACK_LATENCY", "ack_latency_seconds", f"by ({sl}) ")
    quantiles("CLUSTER_SERVICE_TIME", "service_time_seconds", f"by ({sl}) ")
    quantiles("CLUSTER_COMMIT_LATENCY", "commit_latency_seconds", f"by ({sl}) ")
    quantiles("MD_PUBLISH_DELAY", "md_publish_delay_seconds", "")
    role = n.get("CLUSTER_ROLE")
    if role:
        rec("lmb:node_role", f"max by ({sl}, {n['MEMBER_LABEL']}, zone) ({role})")
        rec("lmb:shard_leaders", f"sum by ({sl}) ({role} == bool 2)")
    rec("lmb:shard_members_up", f'sum by ({sl}) (up{{job="lmb-node"}})')
    if n.get("CLUSTER_ELECTIONS_TOTAL"):
        rec("lmb:elections:changes1h", f"max by ({sl}) (changes({n['CLUSTER_ELECTIONS_TOTAL']}[1h]))")
    if n.get("CLUSTER_LAST_ELECTION_NS"):
        rec("lmb:failover_seconds:last", f"max by ({sl}) ({n['CLUSTER_LAST_ELECTION_NS']}) * {lat}")
    if n.get("CLUSTER_REPLICATION_LAG_BYTES"):
        rec("lmb:replication_lag_bytes", f"max by ({sl}, {n['MEMBER_LABEL']}) ({n['CLUSTER_REPLICATION_LAG_BYTES']})")
    elif n.get("CLUSTER_COMMIT_POSITION"):
        cp = n["CLUSTER_COMMIT_POSITION"]
        rec("lmb:replication_lag_bytes",
            f"max by ({sl}) ({cp}) - on ({sl}) group_right max by ({sl}, {n['MEMBER_LABEL']}) ({cp})")
    if n.get("CLUSTER_LAST_EVENT_SEQ"):
        ls = n["CLUSTER_LAST_EVENT_SEQ"]
        rec("lmb:event_seq_spread", f"max by ({sl}) ({ls}) - min by ({sl}) ({ls})")
    if n.get("CLUSTER_COMMANDS_TOTAL"):
        rec("lmb:command_rate", f"max by ({sl}) (rate({n['CLUSTER_COMMANDS_TOTAL']}[1m]))")
    if n.get("CLUSTER_SERVICE_BUSY_RATIO"):
        rec("lmb:shard_utilisation", f"max by ({sl}) ({n['CLUSTER_SERVICE_BUSY_RATIO']})")
    elif n.get("CLUSTER_COMMANDS_TOTAL") and n.get("CLUSTER_SERVICE_TIME"):
        # estimate: commands/s x median service time
        rec("lmb:shard_utilisation",
            f"max by ({sl}) (rate({n['CLUSTER_COMMANDS_TOTAL']}[1m]) * ignoring({ql}) "
            f"{n['CLUSTER_SERVICE_TIME']}{{{ql}=\"{n['Q_P50']}\"}}) * {lat}")
    if n.get("CLUSTER_SNAPSHOT_TIMESTAMP_SECONDS"):
        rec("lmb:snapshot_age_seconds", f"time() - max by ({sl}) ({n['CLUSTER_SNAPSHOT_TIMESTAMP_SECONDS']})")
    elif n.get("CLUSTER_SNAPSHOT_COUNT"):
        rec("lmb:snapshots:changes26h", f"max by ({sl}) (changes({n['CLUSTER_SNAPSHOT_COUNT']}[26h]))")
    if n.get("BACKUP_LAG_SECONDS"):
        rec("lmb:dr_backup_lag_seconds", f"max by ({sl}) ({n['BACKUP_LAG_SECONDS']})")
    if n.get("GATEWAY_INFLIGHT_DEPTH"):
        cap = n.get("GATEWAY_INFLIGHT_CAPACITY") or n.get("INFLIGHT_CAPACITY_DEFAULT", "4096")
        rec("lmb:gateway_inflight_ratio", f"max by ({sl}) ({n['GATEWAY_INFLIGHT_DEPTH']}) / {cap}")
    if n.get("GATEWAY_REJECTS_TOTAL"):
        rec("lmb:gateway_rejects:rate1m", f"sum by (reason) (rate({n['GATEWAY_REJECTS_TOTAL']}[1m]))")
    if n.get("FEED_GAPS_TOTAL") and n.get("FEED_MESSAGES_TOTAL"):
        rec("lmb:feed_gap_ratio:rate5m",
            f"sum by (venue) (rate({n['FEED_GAPS_TOTAL']}[5m])) / "
            f"clamp_min(sum by (venue) (rate({n['FEED_MESSAGES_TOTAL']}[5m])), 1e-9)")
    if n.get("FEED_VENUE_STALE"):
        rec("lmb:feed_venue_stale", f"max by (venue) ({n['FEED_VENUE_STALE']})")
    if n.get("REPLAYER_DIVERGENCE_TOTAL"):
        rec("lmb:replay_divergence:increase5m", f"sum by ({sl}) (increase({n['REPLAYER_DIVERGENCE_TOTAL']}[5m]))")
    if n.get("REPLAYER_LAG_EVENTS"):
        rec("lmb:replayer_lag_events", f"max by ({sl}) ({n['REPLAYER_LAG_EVENTS']})")
    if n.get("POSTTRADE_SINK_LAG_EVENTS"):
        rec("lmb:posttrade_sink_lag_events", f"max by (sink, {sl}) ({n['POSTTRADE_SINK_LAG_EVENTS']})")
    if n.get("CONTROLPLANE_LOCK_HELD"):
        rec("lmb:controlplane_lock_holders", f"sum ({n['CONTROLPLANE_LOCK_HELD']})")
    if n.get("PTP_OFFSET"):
        rec("lmb:ptp_offset_seconds:abs", f"max by (instance) (abs({n['PTP_OFFSET']})) * {n['PTP_OFFSET_TO_SECONDS']}")
    return {"groups": [{"name": "lmb-recording", "interval": "5s", "rules": rules}]}



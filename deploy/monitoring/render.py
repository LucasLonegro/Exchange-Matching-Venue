def read_env(path):
    out = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.split(" #", 1)[0].split("\t#", 1)[0].strip()
            out[k.strip()] = v
    return out


def read_properties(path):
    props = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line[0] in "#!":
                continue
            for i, ch in enumerate(line):
                if ch in "=:" or ch.isspace():
                    k, v = line[:i], line[i + 1:].strip()
                    if v[:1] in "=:":
                        v = v[1:].strip()
                    props[k] = v
                    break
    return props


class Topo:
    """Mirror of io.lmb.common.Topology defaults (file only, no env overrides)."""

    def __init__(self, props):
        self.p = props

    def get(self, k, d):
        return self.p.get(k, d)

    def i(self, k, d):
        return int(self.get(k, d))

    def shards(self): return self.i("lmb.shards", 1)
    def members(self): return self.i("lmb.members", 2)
    def node_host(self, s, m): return self.get(f"lmb.shard.{s}.member.{m}.host", "127.0.0.1")
    def node_zone(self, s, m): return self.get(f"lmb.shard.{s}.member.{m}.zone", "")
    def node_base(self, s, m): return self.i(f"lmb.shard.{s}.member.{m}.basePort", 20000 + 1000 * s + 100 * m)

    def targets(self, names=None):
        """[(job, host, port, labels)] for every process (or only the given local process names)."""
        t = []
        for s in range(self.shards()):
            for m in range(self.members()):
                lab = {"shard": str(s), "member": str(m)}
                if self.node_zone(s, m):
                    lab["zone"] = self.node_zone(s, m)
                t.append((f"node-{s}-{m}", "lmb-node", self.node_host(s, m), self.node_base(s, m) + 9, lab))
        for i in range(self.i("lmb.gateways", 2)):
            t.append((f"gateway-{i}", "lmb-gateway", self.get(f"lmb.gateway.{i}.host", "127.0.0.1"),
                      self.i(f"lmb.gateway.{i}.metricsPort", 9300 + i), {"instance_id": str(i)}))
        for i in range(self.i("lmb.md.instances", 2)):
            t.append((f"marketdata-{i}", "lmb-marketdata", self.get(f"lmb.md.{i}.host", "127.0.0.1"),
                      self.i(f"lmb.md.{i}.metricsPort", 9520 + i), {"instance_id": str(i), "feed": "AB"[i % 2]}))
        for i in range(self.i("lmb.consolidators", 2)):
            t.append((f"consolidator-{i}", "lmb-consolidator", self.get(f"lmb.consolidator.{i}.host", "127.0.0.1"),
                      self.i(f"lmb.consolidator.{i}.metricsPort", 9600 + i), {"instance_id": str(i)}))
        if self.i("lmb.feedsim.instances", 1) > 0:
            t.append(("feedsim-0", "lmb-feedsim", self.get("lmb.feedsim.host", "127.0.0.1"),
                      self.i("lmb.feedsim.metricsPort", 9650), {"instance_id": "0"}))
        for i in range(self.i("lmb.controlplane.instances", 2)):
            t.append((f"controlplane-{i}", "lmb-controlplane", self.get(f"lmb.controlplane.{i}.host", "127.0.0.1"),
                      self.i(f"lmb.controlplane.{i}.metricsPort", 9710 + i), {"instance_id": str(i)}))
        for i in range(self.i("lmb.posttrade.instances", 1)):
            t.append((f"posttrade-{i}", "lmb-posttrade", self.get(f"lmb.posttrade.{i}.host", "127.0.0.1"),
                      self.i("lmb.posttrade.metricsPort", 9810), {"instance_id": str(i)}))
        rbase = self.i("lmb.replayer.metricsPort", 9900)
        for s in range(self.shards()):
            # one replayer per shard; local runs pass -Dlmb.replayer.metricsPort=base+shard
            t.append((f"replayer-{s}", "lmb-replayer", self.get(f"lmb.replayer.{s}.host", "127.0.0.1"),
                      self.i(f"lmb.replayer.{s}.metricsPort", rbase + s), {"shard": str(s)}))
        if names is not None:
            t = [x for x in t if x[0] in names]
        return t



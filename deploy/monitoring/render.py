# alerts: only lmb:* series and up
def alerts(slo, recorded, profile):
    rules = []
    sl = "shard"

    def alert(name, expr, for_, severity, summary, needs=()):
        if any(r not in recorded for r in needs):
            return
        rules.append({"alert": name, "expr": expr, "for": for_,
                      "labels": {"severity": severity, "profile": profile},
                      "annotations": {"summary": summary, "runbook": "docs/operations.md"}})

    lf = slo.get("LATENCY_FOR", "2m")
    for q, sev, f in (("p50", "warning", lf), ("p99", "warning", lf), ("p999", "page", "5m")):
        thr = slo.get(f"ACK_{q.upper()}_SECONDS")
        if thr:
            alert(f"LmbAckLatency{q.upper()}High", f"lmb:ack_latency_seconds:{q} > {thr}", f, sev,
                  f"Ack latency {q} above {thr}s (shard {{{{ $labels.{sl} }}}}): {{{{ $value | humanizeDuration }}}}",
                  [f"lmb:ack_latency_seconds:{q}"])
    if slo.get("SERVICE_TIME_P99_SECONDS"):
        alert("LmbMatcherServiceTimeHigh", f"lmb:service_time_seconds:p99 > {slo['SERVICE_TIME_P99_SECONDS']}", lf,
              "warning", "Matcher p99 time per command high on shard {{ $labels.shard }}", ["lmb:service_time_seconds:p99"])
    if slo.get("COMMIT_P99_SECONDS"):
        alert("LmbCommitLatencyHigh", f"lmb:commit_latency_seconds:p99 > {slo['COMMIT_P99_SECONDS']}", lf, "warning",
              "Commit latency p99 high on shard {{ $labels.shard }}", ["lmb:commit_latency_seconds:p99"])
    if slo.get("MD_DELAY_P99_SECONDS"):
        alert("LmbMarketDataPublishDelayHigh", f"lmb:md_publish_delay_seconds:p99 > {slo['MD_DELAY_P99_SECONDS']}", lf,
              "warning", "Market data publish delay p99 high", ["lmb:md_publish_delay_seconds:p99"])
    alert("LmbShardNoLeader", "lmb:shard_leaders < 1", slo.get("NO_LEADER_FOR", "5s"), "page",
          "Shard {{ $labels.shard }} has no leader: no orders are accepted (failover not completing)", ["lmb:shard_leaders"])
    alert("LmbShardMultipleLeaders", "lmb:shard_leaders > 1", "30s", "warning",
          "Shard {{ $labels.shard }}: more than one member reports LEADER (stale partitioned leader?)", ["lmb:shard_leaders"])
    if slo.get("FAILOVER_SECONDS"):
        alert("LmbFailoverSlow", f"lmb:failover_seconds:last > {slo['FAILOVER_SECONDS']} and changes(lmb:failover_seconds:last[15m]) > 0",
              "0s", "warning", "Last election on shard {{ $labels.shard }} took {{ $value }}s", ["lmb:failover_seconds:last"])
    if slo.get("ELECTIONS_PER_HOUR"):
        alert("LmbFrequentElections", f"lmb:elections:changes1h > {slo['ELECTIONS_PER_HOUR']}", "0s", "warning",
              "Shard {{ $labels.shard }} elected leaders {{ $value }} times in an hour", ["lmb:elections:changes1h"])
    alert("LmbShardMemberDown", f"lmb:shard_members_up < {slo.get('MEMBERS', '3')}", slo.get("MEMBER_DOWN_FOR", "30s"),
          slo.get("MEMBER_DOWN_SEVERITY", "page"),
          "Shard {{ $labels.shard }} runs on {{ $value }} members: no further failure tolerated", ["lmb:shard_members_up"])
    if slo.get("PREFERRED_LEADER_ZONE"):
        alert("LmbLeaderOutsidePreferredZone", f'lmb:node_role{{zone!="{slo["PREFERRED_LEADER_ZONE"]}"}} == 2', "5m", "warning",
              "Leader of shard {{ $labels.shard }} is in {{ $labels.zone }}: steer it back (runbook 4.4)", ["lmb:node_role"])
    alert("LmbReplayDivergence", "lmb:replay_divergence:increase5m > 0", "0s", "page",
          "Shadow replayer DIVERGED on shard {{ $labels.shard }}: determinism broken, stop and investigate",
          ["lmb:replay_divergence:increase5m"])
    alert("LmbEventStreamMembersDisagree", f"lmb:event_seq_spread > {slo.get('EVENT_SEQ_SPREAD', '100000')}", "2m", "warning",
          "Members of shard {{ $labels.shard }} differ by {{ $value }} events", ["lmb:event_seq_spread"])
    if slo.get("REPLAYER_LAG_EVENTS"):
        alert("LmbReplayerLagging", f"lmb:replayer_lag_events > {slo['REPLAYER_LAG_EVENTS']}", "5m", "warning",
              "Replayer of shard {{ $labels.shard }} is {{ $value }} events behind", ["lmb:replayer_lag_events"])
    if slo.get("FEED_GAP_RATIO"):
        alert("LmbFeedGapRateHigh", f"lmb:feed_gap_ratio:rate5m > {slo['FEED_GAP_RATIO']}", "5m", "warning",
              "Feed gap ratio {{ $value }} for venue {{ $labels.venue }}", ["lmb:feed_gap_ratio:rate5m"])
    alert("LmbFeedVenueStale", "lmb:feed_venue_stale > 0", "1m", "warning",
          "Venue {{ $labels.venue }} excluded from NBBO as stale", ["lmb:feed_venue_stale"])
    if slo.get("PTP_WARN_SECONDS"):
        alert("LmbPtpOffsetHigh", f"lmb:ptp_offset_seconds:abs > {slo['PTP_WARN_SECONDS']}", "1m", "warning",
              "PTP offset {{ $value }}s on {{ $labels.instance }}", ["lmb:ptp_offset_seconds:abs"])
        alert("LmbPtpOffsetCritical", f"lmb:ptp_offset_seconds:abs > {slo['PTP_PAGE_SECONDS']}", "30s", "page",
              "PTP offset above the regulatory limit on {{ $labels.instance }}", ["lmb:ptp_offset_seconds:abs"])
    if slo.get("REPLICATION_LAG_BYTES"):
        alert("LmbReplicationLagHigh", f"lmb:replication_lag_bytes > {slo['REPLICATION_LAG_BYTES']}", "30s", "warning",
              "Member {{ $labels.member }} of shard {{ $labels.shard }} is {{ $value | humanize1024 }}B behind",
              ["lmb:replication_lag_bytes"])
    if slo.get("DR_LAG_SECONDS"):
        alert("LmbDrBackupLagHigh", f"lmb:dr_backup_lag_seconds > {slo['DR_LAG_SECONDS']}", "1m", "page",
              "DR backup of shard {{ $labels.shard }} is {{ $value }}s behind: that is the current RPO",
              ["lmb:dr_backup_lag_seconds"])
    if slo.get("INFLIGHT_RATIO"):
        alert("LmbGatewayInflightNearFull", f"lmb:gateway_inflight_ratio > {slo['INFLIGHT_RATIO']}", "30s", "warning",
              "Gateway in-flight queue for shard {{ $labels.shard }} at {{ $value | humanizePercentage }}",
              ["lmb:gateway_inflight_ratio"])
    if slo.get("UTILISATION"):
        alert("LmbShardUtilisationHigh", f"lmb:shard_utilisation > {slo['UTILISATION']}", "10m", "warning",
              "Shard {{ $labels.shard }} matcher busy {{ $value | humanizePercentage }}: plan a cutover (runbook 4.7)",
              ["lmb:shard_utilisation"])
    alert("LmbNoRecentSnapshot", "lmb:snapshots:changes26h == 0", "1h", "warning",
          "Shard {{ $labels.shard }} took no snapshot in 26h (recovery would replay a long log)", ["lmb:snapshots:changes26h"])
    if slo.get("SINK_LAG_EVENTS"):
        alert("LmbPostTradeSinkLag", f"lmb:posttrade_sink_lag_events > {slo['SINK_LAG_EVENTS']}", "5m", "warning",
              "Post-trade sink {{ $labels.sink }} behind on shard {{ $labels.shard }}", ["lmb:posttrade_sink_lag_events"])
    alert("LmbControlPlaneLockHolders", "lmb:controlplane_lock_holders != 1", "1m", "page",
          "{{ $value }} control plane instances hold the scheduler lock (want exactly 1)", ["lmb:controlplane_lock_holders"])
    rules.append({"alert": "LmbTargetDown", "expr": 'up{job=~"lmb-.*"} == 0', "for": slo.get("TARGET_DOWN_FOR", "1m"),
                  "labels": {"severity": "warning", "profile": profile},
                  "annotations": {"summary": "{{ $labels.job }} {{ $labels.instance }} is not answering /metrics",
                                  "runbook": "docs/operations.md"}})
    return {"groups": [{"name": f"lmb-slo-{profile}", "rules": rules}]}



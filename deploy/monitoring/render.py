# dashboard
def dashboard(recorded):
    panels = []
    y = [0]
    pid = [1]

    def row(title):
        panels.append({"type": "row", "title": title, "id": pid[0], "collapsed": False,
                       "gridPos": {"h": 1, "w": 24, "x": 0, "y": y[0]}, "panels": []})
        pid[0] += 1
        y[0] += 1

    slot = [0]

    def ts(title, exprs, unit, w=12, kind="timeseries"):
        exprs = [(e, l) for e, l in exprs if e.split("{")[0].split(" ")[0] in recorded or e.startswith("up")]
        if not exprs:
            return
        x = slot[0]
        if x + w > 24:
            x = 0
            y[0] += 8
        panels.append({"type": kind, "title": title, "id": pid[0],
                       "datasource": {"type": "prometheus", "uid": "${datasource}"},
                       "gridPos": {"h": 8, "w": w, "x": x, "y": y[0]},
                       "fieldConfig": {"defaults": {"unit": unit}, "overrides": []},
                       "options": {"legend": {"displayMode": "table", "placement": "right"}} if kind == "timeseries" else {},
                       "targets": [{"refId": chr(65 + i), "expr": e, "legendFormat": l} for i, (e, l) in enumerate(exprs)]})
        pid[0] += 1
        slot[0] = x + w
        if slot[0] >= 24:
            slot[0] = 0
            y[0] += 8

    def end_row():
        if slot[0]:
            y[0] += 8
            slot[0] = 0

    sh = 'shard=~"$shard"'
    row("Shards")
    ts("Leaders per shard", [("lmb:shard_leaders{" + sh + "}", "shard {{shard}}")], "short", 8, "stat")
    ts("Members up per shard", [("lmb:shard_members_up{" + sh + "}", "shard {{shard}}")], "short", 8, "stat")
    ts("Leader zone", [("lmb:node_role{" + sh + "} == 2", "shard {{shard}} m{{member}} {{zone}}")], "short", 8, "table")
    end_row()
    row("Latency")
    for q in ("p50", "p99", "p999"):
        ts(f"Ack latency {q}", [(f"lmb:ack_latency_seconds:{q}", "shard {{shard}}")], "s", 8)
    end_row()
    ts("Matcher time per command", [(f"lmb:service_time_seconds:{q}{{{sh}}}", q + " shard {{shard}}") for q in ("p50", "p99", "p999")], "s")
    ts("Commit latency", [(f"lmb:commit_latency_seconds:{q}{{{sh}}}", q + " shard {{shard}}") for q in ("p50", "p99", "p999")], "s")
    ts("Market data publish delay", [(f"lmb:md_publish_delay_seconds:{q}", q) for q in ("p50", "p99", "p999")], "s")
    end_row()
    row("Throughput and capacity")
    ts("Commands/s per shard", [("lmb:command_rate{" + sh + "}", "shard {{shard}}")], "ops")
    ts("Matcher utilisation", [("lmb:shard_utilisation{" + sh + "}", "shard {{shard}}")], "percentunit")
    ts("Gateway in-flight (fraction of max)", [("lmb:gateway_inflight_ratio{" + sh + "}", "shard {{shard}}")], "percentunit")
    ts("Gateway rejects/s", [("lmb:gateway_rejects:rate1m", "{{reason}}")], "ops")
    end_row()
    row("Replication, failover, DR")
    ts("Replication lag", [("lmb:replication_lag_bytes{" + sh + "}", "shard {{shard}} m{{member}}")], "bytes")

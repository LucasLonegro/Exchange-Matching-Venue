# scrape configs
def static_scrape(topo, interval):
    jobs = {}
    for _, job, host, port, labels in topo.targets():
        jobs.setdefault(job, []).append({"targets": [f"{host}:{port}"], "labels": labels})
    cfg = {
        "global": {"scrape_interval": interval, "evaluation_interval": interval, "external_labels": {"venue": "lmb"}},
        "rule_files": ["rules/recording-rules.yml", "rules/alerts-prod.yml"],
        "alerting": {"alertmanagers": [{"static_configs": [{"targets": ["alertmanager-1:9093", "alertmanager-2:9093"]}]}]},
        "scrape_configs": [{"job_name": j, "honor_labels": True, "static_configs": sc} for j, sc in jobs.items()],
    }
    hosts = sorted({t[2] for t in topo.targets()})
    cfg["scrape_configs"].append({"job_name": "node-exporter",
                                  "static_configs": [{"targets": [f"{h}:9400" for h in hosts]}]})
    return cfg



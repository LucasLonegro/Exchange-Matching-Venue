def render_all():
    names = read_env(os.path.join(HERE, "metric-names.env"))
    rr = recording_rules(names)
    recorded = {r["record"] for r in rr["groups"][0]["rules"]}
    out = {
        "recording-rules.yml": HEADER + to_yaml(rr) + "\n",
        "grafana-dashboard.json": json.dumps(dashboard(recorded), indent=2) + "\n",
        "prometheus-k8s.yml": HEADER + to_yaml(k8s_scrape()) + "\n",
    }
    for profile in ("prod", "local"):
        slo = read_env(os.path.join(HERE, f"slo-{profile}.env"))
        out[f"alerts-{profile}.yml"] = HEADER + to_yaml(alerts(slo, recorded, profile)) + "\n"
    prod_topo = os.path.join(ROOT, "deploy", "prod", "topology-prod.properties")
    if os.path.exists(prod_topo):
        out["prometheus-prod.yml"] = (HEADER + "# Targets from deploy/prod/topology-prod.properties.\n"
                                      + to_yaml(static_scrape(Topo(read_properties(prod_topo)), "5s")) + "\n")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", default="all", choices=["all", "check", "file-sd"])
    ap.add_argument("--topology")
    ap.add_argument("--local-run", help="start-order file: only these processes are targets")
    ap.add_argument("--out")
    a = ap.parse_args()
    if a.cmd == "file-sd":
        topo = Topo(read_properties(a.topology))
        names = None
        if a.local_run and os.path.exists(a.local_run):
            with open(a.local_run) as f:
                names = {line.split()[1] for line in f if line.strip()}
        sd = [{"targets": [f"{h}:{p}"], "labels": dict(lab, job=job, process=n)} for n, job, h, p, lab in topo.targets(names)]
        with open(a.out, "w") as f:
            json.dump(sd, f, indent=1)
        return 0
    files = render_all()
    if a.cmd == "check":
        stale = [n for n, c in files.items()
                 if not os.path.exists(os.path.join(GEN, n)) or open(os.path.join(GEN, n)).read() != c]
        if stale:
            print("out of date (run python3 deploy/monitoring/render.py): " + ", ".join(stale))
            return 1
        print("deploy/monitoring/generated is up to date")
        return 0
    os.makedirs(GEN, exist_ok=True)
    for n, c in files.items():
        with open(os.path.join(GEN, n), "w") as f:
            f.write(c)
        print("wrote deploy/monitoring/generated/" + n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
